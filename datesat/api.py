"""
Unified API for DateSAT.

This module provides a unified interface to the DateSAT encodings, all of which
translate into Z3 integer arithmetic.
"""

from typing import Any, Dict, List, Union

from z3 import BoolRef

from .core import Date, Period


class DateSATBuilder:
    """Unified API for DateSAT constraint solving."""

    def __init__(
        self,
        approach: str = "epoch_days",
        implementation: str = "int",
        timeout_ms: int = 600000,
        use_maxsat: bool = False,
        python_bounds: bool = False,
    ):
        """Initialize the builder with the specified approach, implementation, and timeout.

        Args:
            approach: Either "simple", "epoch_days", "hybrid_init_ymd", "hybrid_init_epoch", or "alpha_beta"
            implementation: "int", the only implementation (kept for compatibility)
            timeout_ms: Timeout in milliseconds (default: 600000 = 10 minutes)
            use_maxsat: If True, use MaxSAT optimization with soft constraints for dates near today
            python_bounds: If True, bound every date variable and every
                Date + Period result to Python's datetime.date range (years
                1..9999), and build the Date objects of the model through
                datetime, as the original implementation did. By default (False)
                dates are unbounded: any calendar-valid proleptic Gregorian date
                is allowed, so models may contain years below 1 or above 9999.
        """
        if approach == "router":
            raise ValueError(
                "the router approach picks an encoding from the whole constraint, so it is "
                "only available through datesat.solve(..., approach='router')"
            )
        self.approach = approach
        self.implementation = implementation
        self.timeout_ms = timeout_ms
        self.use_maxsat = use_maxsat
        self.python_bounds = python_bounds
        if implementation != "int":
            raise ValueError(f"Unknown implementation: {implementation}. Must be 'int'")

        from .symbolic_int.alpha_beta_int import AlphaBetaSolver
        from .symbolic_int.simple_int import SimpleSolver
        from .symbolic_int.epoch_days_int import EpochDaysSolver
        from .symbolic_int.hybrid_init_epoch_int import HybridInitEpochSolver
        from .symbolic_int.hybrid_init_ymd_int import HybridInitYmdSolver

        kwargs = dict(timeout_ms=timeout_ms, use_maxsat=use_maxsat, python_bounds=python_bounds)
        if approach == "simple":
            self.solver = SimpleSolver(**kwargs)
        elif approach == "epoch_days":
            self.solver = EpochDaysSolver(**kwargs)
        elif approach == "hybrid_init_ymd":
            self.solver = HybridInitYmdSolver(**kwargs)
        elif approach == "hybrid_init_epoch":
            self.solver = HybridInitEpochSolver(**kwargs)
        elif approach == "alpha_beta":
            self.solver = AlphaBetaSolver(**kwargs)
        else:
            raise ValueError(
                f"Unknown approach: {approach}. Must be 'simple', 'epoch_days', 'hybrid_init_ymd', 'hybrid_init_epoch', or 'alpha_beta'"
            )

        self.constraints = []
        self._print_smt_on_solve = False
        
        # Track Int and Bool variables for complete solution extraction
        self.int_vars = {}  # name -> z3 var
        self.bool_vars = {}  # name -> z3 var

    def add_date_var(self, name: str) -> "DateVar":
        """Solver handles date variables internally."""
        return self.solver.add_date_var(name)

    def add_int_var(self, name: str, min_value: int = None, max_value: int = None) -> Any:
        """Add a symbolic Int variable, unbounded unless min_value / max_value are given."""
        from z3 import Int
        var = Int(name)
        if min_value is not None:
            self.solver.add_constraint(var >= min_value)
        if max_value is not None:
            self.solver.add_constraint(var <= max_value)

        # Track this variable for solution extraction
        self.int_vars[name] = var
        return var

    def add_bool_var(self, name: str) -> Any:
        """Add a symbolic bool variable."""
        from z3 import Bool
        var = Bool(name)
        
        # Track this variable for solution extraction
        self.bool_vars[name] = var
        return var

    def add_constraint(self, constraint: Any) -> None:
        """Add a constraint to the solver.

        Accepts Z3 BoolRef constraints.
        """
        # Guard against None constraints
        if constraint is None:
            raise TypeError(
                "Constraint is None. Ensure expressions return a valid constraint."
            )
        self.constraints.append(constraint)
        self.solver.add_constraint(constraint)

    def solve(self) -> Dict[str, Any]:
        """Solve the constraints and return results."""
        if self._print_smt_on_solve:
            print("\n; SMT-LIB dump (generated by DateSAT)")
            print(self.to_smt2())
        result = self.solver.solve()
        if result["status"] == "sat":
            # Extract Int and Bool variables from the Z3 model
            model = self.solver.model()
            int_values = {}
            bool_values = {}
            
            # Explicitly evaluate all tracked Int variables with model_completion=True
            # to ensure we get values for unconstrained variables
            for name, var in self.int_vars.items():
                try:
                    value = model.evaluate(var, model_completion=True)
                    if value is not None:
                        int_values[name] = value.as_long()
                except Exception:
                    # Skip if we can't extract the value
                    pass
            
            # Explicitly evaluate all tracked Bool variables with model_completion=True
            for name, var in self.bool_vars.items():
                try:
                    value = model.evaluate(var, model_completion=True)
                    if value is not None:
                        bool_values[name] = bool(value)
                except Exception:
                    # Skip if we can't extract the value
                    pass
            
            # Add Int and Bool values to result
            if int_values:
                result["ints"] = int_values
            if bool_values:
                result["bools"] = bool_values
            
            print(f"✅ SATISFIABLE:")
            for name, date in result["dates"].items():
                print(f"  {name} = {date}")
            for name, value in result.get("ints", {}).items():
                print(f"  {name} = {value}")
            for name, value in result.get("bools", {}).items():
                print(f"  {name} = {value}")
        else:
            print("❌ UNSATISFIABLE")
        return result

    def get_constraints(self) -> List[BoolRef]:
        """Get all constraints."""
        return self.constraints

    def to_smt2(self) -> str:
        """Return the current problem in SMT-LIB v2 format."""
        # In MaxSAT mode many solvers use Z3 Optimize, which may not expose `to_smt2()`
        # depending on Z3 build/bindings. Fall back to `sexpr()` so callers (e.g. benchmarks)
        # can still persist a textual solver dump.
        inner = getattr(self.solver, "solver", None)
        if inner is not None:
            to_smt2 = getattr(inner, "to_smt2", None)
            if callable(to_smt2):
                return to_smt2()
            sexpr = getattr(inner, "sexpr", None)
            if callable(sexpr):
                return sexpr()
        # Fallback to the solver wrapper API (legacy)
        return self.solver.to_smt2()

    def enable_smtlib_print(self, enabled: bool = True) -> None:
        """Enable or disable printing SMT-LIB when solving."""
        self._print_smt_on_solve = enabled
